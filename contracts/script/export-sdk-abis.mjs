#!/usr/bin/env node
/**
 * C9 SDK ABI generator: reads Foundry artifacts from contracts/out/ and writes
 * typed ABI exports into packages/sdk/src/abis.ts.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "../..");
const outDir = path.join(repoRoot, "contracts", "out");
const targetFile = path.join(repoRoot, "packages", "sdk", "src", "abis.ts");

const CONTRACTS = [
  ["NTIRegistry", "ntiRegistryAbi"],
  ["NTITestToken", "ntiTestTokenAbi"],
  ["Staking", "stakingAbi"],
  ["ConfigRegistry", "configRegistryAbi"],
  ["OracleCommit", "oracleCommitAbi"],
  ["Dispute", "disputeAbi"],
  ["NarrativeMarket", "narrativeMarketAbi"],
  ["FeeRouter", "feeRouterAbi"],
  ["BuybackAdapterV3", "buybackAdapterV3Abi"],
  ["BuybackAdapterV4", "buybackAdapterV4Abi"],
  ["BasketFactory", "basketFactoryAbi"],
  ["Basket", "basketAbi"],
  ["Grants", "grantsAbi"],
  ["NTIGovernor", "ntiGovernorAbi"],
  ["NTITimelock", "ntiTimelockAbi"],
  ["InsuranceFund", "insuranceFundAbi"],
  ["KOLRegistry", "kolRegistryAbi"],
];

const chunks = [
  "// AUTO-GENERATED by contracts/script/export-sdk-abis.mjs from contracts/out/*.json.",
  "// Do not edit manually; re-run `pnpm sdk:abis` after contract changes.",
  "",
];

for (const [contractName, exportName] of CONTRACTS) {
  const artifactPath = path.join(outDir, `${contractName}.sol`, `${contractName}.json`);
  if (!fs.existsSync(artifactPath)) {
    throw new Error(`Missing Foundry artifact: ${artifactPath}. Run forge build --root contracts first.`);
  }
  const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
  chunks.push(`export const ${exportName} = ${JSON.stringify(artifact.abi)} as const;`);
  chunks.push("");
}

chunks.push(
  `export const NTI_ABIS = {`,
  ...CONTRACTS.map(([contractName, exportName]) => `  ${contractName}: ${exportName},`),
  `} as const;`,
  "",
);

fs.writeFileSync(targetFile, chunks.join("\n"), "utf8");
console.log(`Exported ${CONTRACTS.length} contract ABIs to ${path.relative(repoRoot, targetFile)}`);
